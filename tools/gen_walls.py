# Generates the pre-rendered maze wall bitmap (rounded outlines + dithered shading)
import numpy as np, sys
from scipy import ndimage as nd
maze=[l.rstrip('\n') for l in open(sys.argv[1])]
variant=sys.argv[2] if len(sys.argv)>2 else 'A'
T=10; MH=len(maze); MW=len(maze[0]); P=20
H,W=MH*T,MW*T
wall=np.ones((H+2*P,W+2*P),bool)
for ty,row in enumerate(maze):
    for tx,c in enumerate(row):
        if c!='#':
            wall[P+ty*T:P+ty*T+T, P+tx*T:P+tx*T+T]=False
            if c in ' .o' and (tx==0 or tx==MW-1):  # tunnel continues off screen
                if tx==0: wall[P+ty*T:P+ty*T+T, :P]=False
                else: wall[P+ty*T:P+ty*T+T, P+W:]=False
dist=nd.distance_transform_edt(wall)
I0=dist>=3
def disk(r):
    y,x=np.ogrid[-r:r+1,-r:r+1]; return x*x+y*y<=r*r+r*0.8
# round all corners: blur the inset shape and threshold it
I=(nd.gaussian_filter(I0.astype(float),2.6)>0.5)|nd.binary_opening(I0,structure=disk(1))
I&=wall
outline=I&~nd.binary_erosion(I,structure=nd.generate_binary_structure(2,1),border_value=1)
J=nd.binary_erosion(I,structure=np.ones((3,3)),iterations=2,border_value=1)
bayer=np.array([[0,8,2,10],[12,4,14,6],[3,11,1,9],[15,7,13,5]])
yy,xx=np.mgrid[0:wall.shape[0],0:wall.shape[1]]
thr=(bayer[(yy-P)%4,(xx-P)%4]+0.5)/16
# distances to the island edge looking down/right and up/left
def run(mask,dy,dx,maxk=6):
    k=np.full(mask.shape,maxk+1)
    for s in range(maxk,0,-1):
        sh=np.ones_like(mask)
        ys=slice(max(0,-dy*s),mask.shape[0]-max(0,dy*s)); yd=slice(max(0,dy*s),mask.shape[0]-max(0,-dy*s))
        xs=slice(max(0,-dx*s),mask.shape[1]-max(0,dx*s)); xd=slice(max(0,dx*s),mask.shape[1]-max(0,-dx*s))
        sh[ys,xs]=mask[yd,xd]
        k[~sh]=s
    return k
sd=np.minimum(run(I,1,0),run(I,0,1)); sd=np.minimum(sd,run(I,1,1))
hd=np.minimum(run(I,-1,0),run(I,0,-1))
level=np.zeros(wall.shape)
if variant=='A':
    level[J]=0.30
    level[J&(hd<=3)]=0.10
    level[J&(sd<=5)]=0.50
    level[J&(sd<=3)]=0.75
    img=outline|(J&(level>thr))
else:
    level[J]=0.30
    # drop shadow cast onto the floor, down and to the right
    sh=np.zeros_like(I)
    for k in (1,2,3):
        s=np.zeros_like(I); s[k:,k:]=I[:-k,:-k]; sh|=s
    floor=~I & ~nd.binary_dilation(I,iterations=1)  # keep 1px white gap around outline? no: just outside
    floor=~wall
    shadow=sh&floor
    img=outline|(J&(level>thr))|(shadow&(0.5>thr))
img=img[P:P+H,P:P+W]
np.save(f'walls_{variant}.npy',img)
# C header
rowb=(W+7)//8
out=[f'// generated by tools/gen_walls.py (variant {variant})',f'#define WALL_BMP_W {W}',f'#define WALL_BMP_H {H}',f'#define WALL_BMP_STRIDE {rowb}','static const uint8_t wall_bmp[] = {']
for y in range(H):
    b=[]
    for x0 in range(0,W,8):
        v=0
        for i in range(8):
            if x0+i<W and img[y,x0+i]: v|=1<<i
        b.append(v)
    out.append(' '+','.join(f'0x{v:02x}' for v in b)+',')
out.append('};')
open(f'walls_{variant}.h','w').write('\n'.join(out)+'\n')
print(variant,'black px',int(img.sum()))
